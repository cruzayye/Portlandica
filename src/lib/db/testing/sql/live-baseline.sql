-- Approximation of the live public schema these migrations run on top of: the tables as
-- they exist today, with inventory access as the sign-in branch's migrations leave it
-- (anyone can read, partners can write). Column types are a best guess; `supabase db pull`
-- captures the real ones.

create table public.inventory (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text,
  count bigint,
  "isCustom" boolean default false,
  "isStill" boolean,
  "fillDate" date,
  "totalCost" numeric,
  "invoiceNumber" text,
  source text,
  "initialCount" bigint
);

create function public.inventory_set_initial_count()
returns trigger
language plpgsql
as $$
begin
  new."initialCount" := new.count;
  return new;
end
$$;

create trigger inventory_set_initial_count
  before insert on public.inventory
  for each row execute function public.inventory_set_initial_count();

alter table public.inventory enable row level security;

create policy "public can read inventory"
  on public.inventory for select to anon using (true);

create policy "Partners can manage inventory"
  on public.inventory for all to authenticated
  using ((select public.is_partner())) with check ((select public.is_partner()));

-- Legacy tables the app no longer uses.
create table public.orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "isBusiness" boolean,
  "isNewBusiness" boolean,
  "isDTC" boolean,
  name text,
  "isStill" boolean,
  "isSpark" boolean,
  "totalStill" bigint,
  "totalSpark" bigint,
  "IsCustomStill" boolean,
  "isCustomSpark" boolean,
  price numeric,
  "isPaid" boolean,
  "createInvoice" boolean,
  notes text,
  "businessType" text,
  "streetAddress" text,
  city text,
  state text,
  zip text,
  "deliveryType" text,
  "isDonation" boolean
);

create table public.location_types (
  id bigint generated by default as identity primary key,
  name text
);

create table public.locations (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text,
  address text,
  latitude double precision,
  longitude double precision,
  type bigint references public.location_types (id)
);

alter table public.orders enable row level security;
alter table public.location_types enable row level security;
alter table public.locations enable row level security;

